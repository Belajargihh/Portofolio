let currentLang = 'id';

export function getCurrentLang() {
  return currentLang;
}

export function getTranslation(keyPath, lang = currentLang) {
  const keys = keyPath.split('.');
  let val = translations[lang] || translations.id;
  for (const k of keys) {
    if (val && val[k] !== undefined) {
      val = val[k];
    } else {
      return '';
    }
  }
  return val;
}

/**
 * Helper to get localized string from an object like { id: '...', eng: '...' }
 * or return the string as-is if already a plain string.
 */
export function localize(data, lang = currentLang) {
  if (!data) return '';
  if (typeof data === 'string') return data;
  if (typeof data === 'object') {
    return data[lang] || data.id || data.eng || '';
  }
  return String(data);
}

/**
 * Apply translations to all DOM elements with data-i18n attributes
 */
export function applyTranslations(lang = currentLang) {
  currentLang = lang;
  document.documentElement.lang = translations[lang]?.meta?.lang || 'id';

  // Update Page Title and Meta Description
  if (translations[lang]?.meta) {
    document.title = translations[lang].meta.title;
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) {
      metaDesc.setAttribute('content', translations[lang].meta.description);
    }
  }

  // Update static elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const text = getTranslation(key, lang);
    if (text) {
      el.innerHTML = text;
    }
  });

  // Update placeholders with data-i18n-placeholder
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const text = getTranslation(key, lang);
    if (text) {
      el.setAttribute('placeholder', text);
    }
  });

  // Update title attributes with data-i18n-title
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const text = getTranslation(key, lang);
    if (text) {
      el.setAttribute('title', text);
    }
  });

  // Update Switcher Active UI State
  const switchBtns = document.querySelectorAll('.lang-btn');
  switchBtns.forEach(btn => {
    const btnLang = btn.getAttribute('data-lang');
    if (btnLang === lang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Re-run Lucide icons if available
  if (window.lucide && typeof window.lucide.createIcons === 'function') {
    try {
      window.lucide.createIcons({ icons: window.lucide });
    } catch (e) {
      console.warn('Lucide createIcons warning:', e);
    }
  }
}

/**
 * Switch language and dispatch notification event
 */
export function setLanguage(lang) {
  if (lang !== 'id' && lang !== 'eng') return;
  currentLang = lang;
  try {
    localStorage.setItem('portfolio_lang', lang);
  } catch (e) {}

  applyTranslations(lang);

  // Dispatch custom event for components to re-render
  window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
}

/**
 * Initialize language switcher component and stored preference
 */
export function initI18n() {
  let savedLang = 'id';
  try {
    savedLang = localStorage.getItem('portfolio_lang') || 'id';
  } catch (e) {}

  if (savedLang !== 'id' && savedLang !== 'eng') {
    savedLang = 'id';
  }

  // Bind click handlers to language buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      if (targetLang && targetLang !== currentLang) {
        setLanguage(targetLang);
      }
    });
  });

  // Apply initial translations
  setLanguage(savedLang);
}
